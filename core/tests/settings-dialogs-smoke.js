const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const { parseHTML } = require('linkedom');
const root = path.resolve(__dirname, '../..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
for (const language of ['zh', 'en']) {
  const { window, document } = parseHTML(read('index.html'));
  let timerId = 0;
  const timers = new Map();
  window.setTimeout = (callback, delay) => { assert.equal(delay, 3000); timers.set(++timerId, callback); return timerId; };
  window.clearTimeout = id => timers.delete(id);
  const context = vm.createContext({ window, document });
  for (const file of [`app/i18n/${language}.js`, 'app/settings-dialogs.js']) vm.runInContext(read(file), context);
  const words = window[language === 'zh' ? 'ClaraCoreTranslationsZh' : 'ClaraCoreTranslationsEn'];
  const t = (key, args = {}) => { assert.equal(typeof words[key], 'string', key); return words[key].replace(/\{(\w+)\}/g, (_, key) => args[key]); };
  const section = document.querySelector('#settingsView');
  const dialog = document.querySelector('#settingsDetailDialog');
  let focused;
  for (const node of document.querySelectorAll('*')) node.focus = () => { focused = node; };
  dialog.showModal = () => { dialog.open = true; };
  dialog.close = () => { dialog.open = false; dialog.dispatchEvent(new window.Event('close')); };
  let dirty = false, busy = false, discarded = 0, opens = 0;
  const controller = window.createClaraCoreSettingsDialogs({ root: section, t, summary: scope => `saved-${scope}`,
    isDirty: () => dirty, isBusy: () => busy, discard: () => { discarded++; dirty = false; }, onOpen: () => opens++ });
  assert.equal(section.querySelectorAll('dialog').length, 1, 'Settings must not nest modal editors');
  assert.equal(section.querySelectorAll('[data-settings-tab]').length, 0);
  assert.equal(document.querySelector('#saveSettings'), null, 'There must be no combined model save');
  for (const node of section.querySelectorAll('[data-i18n]')) t(node.getAttribute("data-i18n"));
  const ids = [...document.querySelectorAll('[id]')].map(node => node.id);
  assert.equal(new Set(ids).size, ids.length, 'Moving form controls must not duplicate IDs');
  for (const entry of section.querySelectorAll('[data-settings-open]')) {
    entry.click();
    assert.equal(dialog.open, true);
    assert.equal(controller.activePanel(), entry.dataset.settingsOpen);
    assert.equal(section.querySelectorAll('[data-settings-editor]:not([hidden])').length, 1);
    const saves = [...section.querySelectorAll('[data-settings-save-for]:not([hidden])')];
    assert.equal(saves.length, entry.dataset.settingsOpen === "models" ? 2 : 1);
    if (entry.dataset.settingsOpen !== "models") assert.equal(saves[0].dataset.settingsSaveFor, entry.dataset.settingsOpen);
    assert.equal(controller.open(entry.dataset.settingsOpen === 'models' ? 'controller' : 'models'), false, 'Only one editor may be active');
    assert.equal(focused.id, 'settingsDialogTitle');
    assert.equal(controller.requestClose(), true);
    assert.equal(focused, entry, 'Closing restores focus to the overview entry');
  }
  assert.equal(opens, 7);
  assert.equal(controller.open('about'), false, 'A short version section must not require a dialog');
  assert.equal(document.querySelector('#checkForUpdates').closest('dialog'), null);
  assert.equal(document.querySelector('#settingsAppVersion').closest('dialog'), null);
  controller.open('reflection'); dirty = true;
  const cancel = new window.Event('cancel', { cancelable: true }); dialog.dispatchEvent(cancel);
  assert.equal(cancel.defaultPrevented, true);
  assert.equal(dialog.open, true);
  assert.equal(section.querySelector('#settingsDiscardPrompt').hidden, false);
  section.querySelector('#settingsKeepEditing').click();
  assert.equal(section.querySelector('#settingsDiscardPrompt').hidden, true);
  controller.saved('reflection');
  assert.equal(dialog.open, true, 'An acknowledgement cannot close a newer unsaved draft');
  busy = true;
  assert.equal(controller.requestClose(), false);
  section.querySelector('#settingsDiscardChanges').click();
  assert.equal(discarded, 0, 'An in-flight operation must not discard its form');
  busy = false; controller.requestClose(); section.querySelector('#settingsDiscardChanges').click();
  assert.equal(discarded, 1); assert.equal(dialog.open, false);
  controller.open('controller'); controller.saved('reflection');
  assert.equal(dialog.open, true, 'A response from another editor must not close the current editor');
  controller.saved('controller'); assert.equal(dialog.open, false);
  assert(section.querySelector('#settingsOverviewNotice').textContent.length > 0);
  const overview = section.querySelector('#settingsOverviewNotice');
  const firstTimer = [...timers.values()][0];
  assert.equal(typeof firstTimer, 'function'); firstTimer();
  assert.equal(overview.textContent, '', 'A success notice must expire after three seconds');
  controller.open('controller'); controller.saved('controller');
  const staleTimer = [...timers.values()].at(-1);
  controller.open('gateway'); assert.equal(overview.textContent, '', 'Opening another editor clears the prior notice');
  controller.saved('gateway'); const newMessage = overview.textContent;
  staleTimer(); assert.equal(overview.textContent, newMessage, 'A cancelled timer must not clear newer feedback');
  controller.clearOverviewNotice(); assert.equal(overview.textContent, '');
  timers.clear();
  controller.open('storage'); controller.saved('storage', 'restart required', { persistent: true });
  assert.equal(overview.textContent, 'restart required');
  assert.equal(timers.size, 0, 'Required restart feedback must not auto-expire');

  assert.equal(document.querySelector('#saveBackupPolicy').getAttribute('form'), 'backupPolicyForm', 'Footer save must retain form submission and validation');
}
console.log('Settings modal DOM regression passed: seven entries and two model forms and inline version/update, independent editors, translations, focus return, unsaved/busy close guards and stale-save protection (no UI automation).');
