// Regenerate derived assets from the maintained SVG sources. No app/UI launch.
const fs = require("node:fs/promises");
const path = require("node:path");
const { execFileSync } = require("node:child_process");
const sharp = require("sharp");

const root = path.resolve(__dirname, "..");
const assets = path.join(root, "assets");
const generated = path.join(assets, "generated");
const iconset = path.join(assets, "icon.iconset");

async function raster(source, size) {
  return sharp(path.join(assets, source), { density: 144 })
    .resize(size, size).ensureAlpha().png().toBuffer();
}

function windowsIcon(images) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  const directory = Buffer.alloc(16 * images.length);
  let offset = header.length + directory.length;
  images.forEach(({ size, png }, index) => {
    const entry = index * 16;
    directory.writeUInt8(size === 256 ? 0 : size, entry);
    directory.writeUInt8(size === 256 ? 0 : size, entry + 1);
    directory.writeUInt16LE(1, entry + 4);
    directory.writeUInt16LE(32, entry + 6);
    directory.writeUInt32LE(png.length, entry + 8);
    directory.writeUInt32LE(offset, entry + 12);
    offset += png.length;
  });
  return Buffer.concat([header, directory, ...images.map(image => image.png)]);
}

async function main() {
  // ICNS is generated by the macOS command-line compiler. Fail before writing
  // any derivatives when this development host cannot build the whole family.
  await fs.access("/usr/bin/iconutil");
  await fs.mkdir(generated, { recursive: true });
  await fs.mkdir(iconset, { recursive: true });
  const sizes = [16, 32, 64, 128, 256, 512, 1024];
  const images = new Map();
  for (const size of sizes) {
    const png = await raster("brand/claracore-mark.svg", size);
    images.set(size, png);
    await fs.writeFile(path.join(generated, `icon-${size}.png`), png);
  }
  const macSizes = [16, 32, 128, 256, 512];
  for (const size of macSizes) {
    await fs.writeFile(path.join(iconset, `icon_${size}x${size}.png`), images.get(size));
    await fs.writeFile(path.join(iconset, `icon_${size}x${size}@2x.png`), images.get(size * 2));
  }
  execFileSync("/usr/bin/iconutil", ["-c", "icns", iconset, "-o", path.join(assets, "icon.icns")], { stdio: "inherit" });
  const windowsSizes = [16, 24, 32, 48, 64, 128, 256];
  const windowsImages = [];
  for (const size of windowsSizes) windowsImages.push({ size, png: images.get(size) || await raster("brand/claracore-mark.svg", size) });
  await fs.writeFile(path.join(assets, "icon.ico"), windowsIcon(windowsImages));
  for (const [source, output] of [
    ["brand/claracore-mark-flat.svg", "icon-flat-1024.png"],
    ["brand/claracore-mark-flat-dark.svg", "icon-flat-dark-1024.png"]
  ]) await fs.writeFile(path.join(generated, output), await raster(source, 1024));
  await sharp(path.join(assets, "brand/claracore-wordmark.svg"), { density: 144 })
    .resize(1800, 520).png().toFile(path.join(generated, "wordmark-1800x520.png"));
  for (const size of [16, 20, 24, 32]) await fs.writeFile(path.join(generated, `tray-color-${size}.png`), await raster("tray/claracore-tray-color.svg", size));
  console.log(JSON.stringify({ ok: true, iconSizes: sizes, windowsSizes, appearances: ["light", "dark"], templateTray: "preserved" }));
}

main().catch(error => { console.error(error); process.exitCode = 1; });
